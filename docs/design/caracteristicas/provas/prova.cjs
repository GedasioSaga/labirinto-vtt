async function abrir(navegador, opcoes = {}) {
  const ctx = await navegador.newContext({ viewport: { width: 1600, height: 960 }, ...opcoes })
  const pg = await ctx.newPage()
  const erros = []
  pg.on('pageerror', (e) => erros.push('pageerror: ' + e.message))
  pg.on('console', (m) => { if (m.type() === 'error') erros.push('console: ' + m.text()) })
  await pg.addInitScript(() => {
    window.__longas = []
    new PerformanceObserver((l) => { for (const e of l.getEntries()) window.__longas.push(Math.round(e.duration)) }).observe({ type: 'longtask', buffered: true })
  })
  await pg.goto(ARQ)
  await pg.waitForTimeout(500)
  return { ctx, pg, erros }
}

